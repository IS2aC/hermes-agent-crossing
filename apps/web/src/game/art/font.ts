export const GLYPH_H = 5;

const glyph = (ch: string) => GLYPHS[ch] ?? GLYPHS[' ']!;

export function textWidth(text: string): number {
  const chars = [...text.toUpperCase()];
  return chars.reduce((w, ch) => w + glyph(ch)[0]!.length + 1, 0) - (chars.length > 0 ? 1 : 0);
}

export function drawText(canvas: PixelCanvas, text: string, x: number, y: number, color: Color): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const rows = glyph(ch);
    rows.forEach((row, j) => [...row].forEach((bit, i) => bit === '1' && canvas.set(cx + i, y + j, color)));
    cx += rows[0]!.length + 1;
  }
}
